"""Submission acceptance examples through the real API, worker and PostgreSQL.

Expectations below are authored from the invoice/order facts, not generated by
the OCR or recommendation code. Every test uses a disposable company schema.
JUnit evidence is retained by scripts/evaluate_submission_edges.py.
"""
from concurrent.futures import ThreadPoolExecutor
from copy import deepcopy
from decimal import Decimal
import hashlib
import json
import os

import pytest

from test_application_postgres import h, ROOT  # shared isolated application harness
from render_workflows import render

pytestmark = pytest.mark.skipif(
    not os.getenv('APPLICATION_TEST_DATABASE_URL'),
    reason='requires explicit real PostgreSQL application test database',
)


def source(case='W01'):
    return deepcopy(json.loads((ROOT/'fixtures/workflows/v1/inputs'/f'{case}.json').read_text())['document'])


def save(record_property, family, expected, observed):
    record_property('edge_evidence', json.dumps({
        'family': family, 'expected': expected, 'observed': observed,
    }, sort_keys=True))


def test_happy_path_and_explicit_pack_size(h, record_property):
    invoice, detail, _ = h.processed('happy')
    result = detail['decision']
    before = h.balance()['remaining_qty']
    approved = h.post('/api/invoices/'+invoice+'/approve', {'expected_decision_version': 1})
    after = h.balance()['remaining_qty']
    save(record_property, 'control', {'bucket': 'accept', 'quantity': '600', 'remaining_after': '0'}, {
        'bucket': result['bucket'], 'normalized_quantity': result['values']['normalized_qty'],
        'remaining_before': before, 'remaining_after': after, 'approval_http_status': approved.status_code,
    })
    assert result['bucket'] == 'accept'
    assert [Decimal(q) for q in result['values']['normalized_qty']] == [Decimal('600')]
    assert approved.status_code == 200 and Decimal(after) == 0


def test_missing_pack_needs_evidence_before_approval(h, record_property):
    invoice, detail, _ = h.processed('missing-pack')
    original = deepcopy(detail['extraction']['fields'])
    blocked = h.post('/api/invoices/'+invoice+'/approve', {'expected_decision_version': 1})
    review = h.post('/api/invoices/'+invoice+'/review', {'expected_decision_version': 1, 'corrections': [
        {'field_path': 'lines[1].pack_factor', 'value': '100',
         'reason': 'Controlled test: simulated reviewer checks a separate supplier specification stating 100 EA per box.'},
    ]})
    assert review.status_code == 202, review.text
    assert h.wait(review.json()['run']['id'])['state'] == 'completed'
    updated = h.client.get('/api/invoices/'+invoice).json()
    save(record_property, 'missing_pack', {'initial_bucket': 'human_review', 'approval_blocked': True,
        'after_supported_review': 'accept', 'original_preserved': True}, {
        'initial_bucket': detail['decision']['bucket'], 'unknown_rules': detail['decision']['unknown_rules'],
        'blocked_approval_http_status': blocked.status_code, 'after_supported_review': updated['decision']['bucket'],
        'original_preserved': updated['extraction']['fields'] == original,
        'review_is_simulated': True,
    })
    assert detail['decision']['bucket'] == 'human_review'
    assert 'unit_conversion' in detail['decision']['unknown_rules']
    assert blocked.status_code == 409
    assert updated['decision']['bucket'] == 'accept' and updated['extraction']['fields'] == original


@pytest.mark.parametrize('incorrect', [False, True], ids=['agreed-prices', 'offsetting-errors'])
def test_same_total_does_not_hide_wrong_item_prices(h, record_property, incorrect):
    doc = source('W05')
    if not incorrect:
        doc['lines'][0].update(unit_price='12.50', amount='2500.00')
        doc['lines'][1].update(unit_price='4.00', amount='800.00')
    _, detail, _ = h.processed(data=render(doc))
    decision = detail['decision']
    checks = decision['findings']['unit_price']['line_checks']
    expected = 'reject' if incorrect else 'accept'
    save(record_property, 'offsetting_prices', {'bucket': expected, 'line_failures': 2 if incorrect else 0}, {
        'bucket': decision['bucket'], 'grand_total': decision['document']['grand_total'],
        'arithmetic_status': decision['findings']['arithmetic']['status'], 'line_price_checks': checks,
    })
    assert decision['bucket'] == expected and decision['findings']['arithmetic']['status'] == 'pass'
    assert [c['status'] for c in checks] == (['fail', 'fail'] if incorrect else ['pass', 'pass'])
    assert [Decimal(c['delta']) for c in checks] == ([Decimal('1'), Decimal('-1')] if incorrect else [Decimal(0), Decimal(0)])


@pytest.mark.parametrize('boxes', [6, 7], ids=['remaining-600', 'over-by-100'])
def test_partial_invoice_uses_remaining_not_original_quantity(h, record_property, boxes):
    doc = source()
    amount = str(boxes * 500) + '.00'
    doc['lines'][0].update(qty=str(boxes), amount=amount)
    doc.update(subtotal=amount, grand_total=amount)
    invoice, detail, _ = h.processed(data=render(doc))
    decision = detail['decision']
    response = h.post('/api/invoices/'+invoice+'/approve', {'expected_decision_version': 1})
    remaining = h.balance()['remaining_qty']
    save(record_property, 'partial_invoices', {'bucket': 'accept' if boxes == 6 else 'reject',
        'remaining_before': '600', 'remaining_after': '0' if boxes == 6 else '600'}, {
        'bucket': decision['bucket'], 'quantity_checks': decision['findings']['remaining_quantity']['line_checks'],
        'approval_http_status': response.status_code, 'remaining_after': remaining,
    })
    assert decision['bucket'] == ('accept' if boxes == 6 else 'reject')
    assert [Decimal(v) for v in decision['values']['remaining_qty']] == [Decimal('600')]
    assert response.status_code == (200 if boxes == 6 else 409)
    assert Decimal(remaining) == (0 if boxes == 6 else 600)
    if boxes == 7:
        assert 'remaining_quantity' in decision['blocking_rules']
        assert [Decimal(v) for v in decision['values']['excess_qty']] == [Decimal('100')]


def test_competing_partial_approvals_cannot_spend_the_same_balance(h, record_property):
    first, a, _ = h.processed('partial-a')
    second, b, _ = h.processed('partial-b')
    with ThreadPoolExecutor(2) as pool:
        responses = list(pool.map(lambda invoice: h.post('/api/invoices/'+invoice+'/approve',
            {'expected_decision_version': 1}), [first, second]))
    statuses = sorted(r.status_code for r in responses)
    loser = [first, second][next(i for i, r in enumerate(responses) if r.status_code == 409)]
    updated = h.client.get('/api/invoices/'+loser).json()['decision']
    remaining = h.balance('0150')['remaining_qty']
    save(record_property, 'partial_invoices', {'initial_buckets': ['accept', 'accept'],
        'approval_http_statuses': [200, 409], 'remaining_after': '200', 'loser_bucket': 'reject'}, {
        'initial_buckets': [a['decision']['bucket'], b['decision']['bucket']],
        'approval_http_statuses': statuses, 'remaining_after': remaining,
        'loser_bucket': updated['bucket'], 'loser_decision_version': updated['version'],
    })
    assert a['decision']['bucket'] == b['decision']['bucket'] == 'accept'
    assert statuses == [200, 409] and Decimal(remaining) == 200
    assert updated['bucket'] == 'reject' and updated['version'] == 2


def test_duplicate_different_pdf_bytes_is_still_detected(h, record_property):
    doc = source()
    first, a, original = h.processed(data=render(doc))
    second, b, copy = h.processed(data=render(doc, 'columnar'), filename='another-layout.pdf')
    rejected = h.post('/api/invoices/'+second+'/approve', {'expected_decision_version': 1})
    approved = h.post('/api/invoices/'+first+'/approve', {'expected_decision_version': 1})
    save(record_property, 'duplicates', {'different_file_hashes': True, 'second_bucket': 'reject',
        'duplicate_status': 'fail', 'first_still_approvable': True}, {
        'different_file_hashes': hashlib.sha256(original).digest() != hashlib.sha256(copy).digest(),
        'first_bucket': a['decision']['bucket'], 'second_bucket': b['decision']['bucket'],
        'duplicate_status': b['decision']['findings']['duplicate']['status'],
        'copy_approval_http_status': rejected.status_code, 'first_approval_http_status': approved.status_code,
    })
    assert original != copy and a['decision']['bucket'] == 'accept'
    assert b['decision']['bucket'] == 'reject' and 'duplicate' in b['decision']['blocking_rules']
    assert rejected.status_code == 409 and approved.status_code == 200


