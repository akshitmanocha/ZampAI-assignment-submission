def test_mobile_scan_keeps_original_and_routes_uncertain_reading_to_review(h, record_property):
    invoice, detail, _ = h.processed('scan')
    original = deepcopy(detail['extraction']['fields'])
    engine = detail['extraction']['pages'][0].get('engine')
    initial = detail['decision']['bucket']
    simulated_review = initial == 'human_review'
    if simulated_review:
        assert original['lines'][0]['description'].get('requires_source_verification')
        response = h.post('/api/invoices/'+invoice+'/review', {'expected_decision_version': 1, 'corrections': [
            {'field_path': 'lines[1].description', 'value': 'GLV-M Nitrile gloves medium [BOX; 100 EA/box]',
             'reason': 'Controlled test: simulated reviewer restores the exact printed pack text; not an OCR accuracy claim.'},
        ]})
        assert response.status_code == 202, response.text
        assert h.wait(response.json()['run']['id'])['state'] == 'completed'
        updated = h.client.get('/api/invoices/'+invoice).json()
    else:
        assert original['lines'][0]['description']['value'] == 'GLV-M Nitrile gloves medium [BOX; 100 EA/box]'
        updated = detail
    save(record_property, 'scan_control', {'engine': 'ppocr-v5-mobile',
        'safe_initial_buckets': ['accept', 'human_review'], 'after_supported_review': 'accept',
        'original_preserved': True}, {
        'engine': engine, 'initial_bucket': initial,
        'original_description_reading': original['lines'][0]['description'],
        'simulated_review_used': simulated_review, 'after_supported_review': updated['decision']['bucket'],
        'original_preserved': updated['extraction']['fields'] == original,
    })
    assert engine == 'ppocr-v5-mobile' and initial in ['accept', 'human_review']
    assert updated['decision']['bucket'] == 'accept' and updated['extraction']['fields'] == original
